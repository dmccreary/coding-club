// Levels of Intelligent Textbook Sophistication
// CANVAS_HEIGHT: 515
// Bloom: Understand (L2), verb "explain"
// Six rungs from a plain PDF up to a conversational AI tutor. The reader steps
// or clicks through them and sees where this book actually sits -- Level 4,
// where a learning graph orders the content but nothing adapts per reader yet.

// ---------- canvas geometry ----------
let containerWidth;
let canvasWidth = 400;
let drawHeight = 470;
let controlHeight = 45;
let canvasHeight = drawHeight + controlHeight;
let containerHeight = canvasHeight;
let margin = 25;
let defaultTextSize = 16;

// ---------- brand palette (fixed by the book's style guide) ----------
const SKY_BLUE = '#4A90D9';
const AMBER = '#F5A623';

// ---------- ladder geometry ----------
const ladderTop = 58;
const rowH = 42;
const barH = 34;
const barX = 30;
const badgeColW = 150;      // right column reserved for the "This book" badge

// The rung this book occupies, as stated in Chapter 2.
const THIS_BOOK_LEVEL = 4;

const levels = [
  {
    name: 'Static Content',
    summary: 'The same fixed words and pictures for every reader, with nothing to click.',
    example: 'A scanned lab manual handed out as a PDF. A reader who is lost has no path other than reading it again.'
  },
  {
    name: 'Hyperlinked and Searchable',
    summary: 'The text moves to the web, gaining navigation, search, and cross-links between sections.',
    example: 'An online documentation site. Readers can jump straight to the section they need instead of paging through.'
  },
  {
    name: 'Interactive Simulations',
    summary: 'Embedded MicroSims let the reader manipulate a concept rather than only read about it.',
    example: 'The cycle diagram in Chapter 1, where you step a single wiring problem through the whole improvement loop.'
  },
  {
    name: 'Learning Graph',
    summary: 'An explicit machine-readable map of every concept and its dependencies orders the whole book.',
    example: 'This book. Each chapter was generated by walking the graph in dependency order, so no chapter assumes a concept you have not met yet.'
  },
  {
    name: 'Personalized Path',
    summary: 'The book tracks what a given reader already knows and routes them past it.',
    example: 'A mentor who already runs a club skips the charter chapter, because the book has recorded that they demonstrated it.'
  },
  {
    name: 'Adaptive AI Tutor',
    summary: 'A conversational tutor generates explanations, hints, and practice on demand for this reader, right now.',
    example: 'A student stuck on polarity asks a question in plain English and gets a worked example built around the exact circuit on their desk.'
  }
];

// ---------- state ----------
let selected = THIS_BOOK_LEVEL - 1;   // zero-based index of the highlighted level
let prevButton, nextButton, resetButton;

function setup() {
  updateCanvasSize();
  const canvas = createCanvas(containerWidth, containerHeight);
  canvas.parent(document.querySelector('main'));
  textSize(defaultTextSize);

  prevButton = createButton('Previous');
  prevButton.position(10, drawHeight + 10);
  prevButton.mousePressed(() => selectLevel(selected - 1));

  nextButton = createButton('Next');
  nextButton.position(95, drawHeight + 10);
  nextButton.mousePressed(() => selectLevel(selected + 1));

  resetButton = createButton('This Book');
  resetButton.position(155, drawHeight + 10);
  resetButton.mousePressed(() => selectLevel(THIS_BOOK_LEVEL - 1));

  describe('A six-level spectrum of intelligent textbook sophistication, from static ' +
           'content up to an adaptive AI tutor, marking the level this book occupies.');
}

function draw() {
  updateCanvasSize();

  fill('aliceblue');
  stroke('silver');
  strokeWeight(1);
  rect(0, 0, canvasWidth, drawHeight);

  fill('white');
  stroke('silver');
  rect(0, drawHeight, canvasWidth, controlHeight);

  drawTitle();
  drawLadder();
  drawDetailPanel();
  drawControlLabel();
}

function drawTitle() {
  noStroke();
  fill('black');
  textAlign(CENTER, TOP);
  textSize(22);
  text('Levels of Intelligent Textbook Sophistication', canvasWidth / 2, 10);
}

// Bar width grows with the level, so "further right" reads as "more capable".
function barWidth(index) {
  const maxW = canvasWidth - barX - badgeColW;
  const minW = min(215, maxW * 0.45);
  return minW + (maxW - minW) * (index / (levels.length - 1));
}

function rowTop(index) {
  return ladderTop + index * rowH;
}

function drawLadder() {
  for (let i = 0; i < levels.length; i++) {
    const y = rowTop(i);
    const w = barWidth(i);
    const isSelected = (i === selected);

    stroke(isSelected ? '#B87B12' : '#2E6BA8');
    strokeWeight(isSelected ? 3 : 1.5);
    fill(isSelected ? AMBER : SKY_BLUE);
    rect(barX, y, w, barH, 6);

    noStroke();
    fill(isSelected ? 'black' : 'white');
    textAlign(LEFT, CENTER);
    textSize(15);
    text('Level ' + (i + 1) + ' - ' + levels[i].name, barX + 12, y + barH / 2);

    // "This book is here" badge, aligned with the rung this book occupies
    if (i === THIS_BOOK_LEVEL - 1) {
      const bx = barX + w + 12;
      const by = y + barH / 2;
      stroke('#B87B12');
      strokeWeight(2);
      fill('white');
      rect(bx, y + 2, badgeColW - 26, barH - 4, 6);
      noStroke();
      fill('#B87B12');
      textAlign(LEFT, CENTER);
      textSize(13);
      text('◀ This book', bx + 8, by);
    }
  }
}

function drawDetailPanel() {
  const top = ladderTop + levels.length * rowH + 14;
  const h = drawHeight - top - 12;
  const level = levels[selected];

  stroke('silver');
  strokeWeight(1);
  fill(255, 255, 255, 230);
  rect(margin / 2, top, canvasWidth - margin, h, 10);

  const left = margin / 2 + 14;
  const maxW = canvasWidth - margin - 28;

  noStroke();
  fill('#B87B12');
  textAlign(LEFT, TOP);
  textSize(17);
  text('Level ' + (selected + 1) + ' - ' + level.name, left, top + 12);

  fill('black');
  textSize(14);
  let y = wrapText(level.summary, left, top + 38, maxW, 20);

  fill('#555555');
  textSize(13);
  wrapText('Example: ' + level.example, left, y + 8, maxW, 18);
}

function drawControlLabel() {
  noStroke();
  fill('black');
  textAlign(LEFT, CENTER);
  textSize(defaultTextSize);
  text('Level ' + (selected + 1) + ' of ' + levels.length +
       '   (click any bar)', 245, drawHeight + controlHeight / 2);
}

// Word-wrap a string into the given width; returns the y below the last line.
function wrapText(str, x, y, maxW, lineHeight) {
  const words = str.split(' ');
  let line = '';
  let cursorY = y;
  for (const word of words) {
    const test = line.length ? line + ' ' + word : word;
    if (textWidth(test) > maxW && line.length) {
      text(line, x, cursorY);
      cursorY += lineHeight;
      line = word;
    } else {
      line = test;
    }
  }
  if (line.length) {
    text(line, x, cursorY);
    cursorY += lineHeight;
  }
  return cursorY;
}

function selectLevel(index) {
  selected = constrain(index, 0, levels.length - 1);
}

function mousePressed() {
  for (let i = 0; i < levels.length; i++) {
    const y = rowTop(i);
    if (mouseY >= y && mouseY <= y + barH &&
        mouseX >= barX && mouseX <= barX + barWidth(i)) {
      selectLevel(i);
      return;
    }
  }
}

// ---------- responsive plumbing (must stay at the end) ----------
function windowResized() {
  updateCanvasSize();
  resizeCanvas(containerWidth, containerHeight);
  redraw();
}

function updateCanvasSize() {
  const container = document.querySelector('main').getBoundingClientRect();
  const w = Math.floor(container.width);
  if (w !== containerWidth) {
    containerWidth = w;
    canvasWidth = containerWidth;
    if (typeof width !== 'undefined' && width > 0) {
      resizeCanvas(containerWidth, containerHeight);
    }
  }
}
